// Enumeração que representa os tipos de campos disponíveis para aplicação de filtros.
export enum EFilterType {
  /** Campo de texto. */
  STRING = "string",
  /** Campo numérico. */
  NUMBER = "number",
  /** Campo de data. */
  DATE = "date",
  /** Campo booleano. */
  BOOLEAN = "boolean",
  /** Campo de seleção. */
  SELECT = "select",
}
